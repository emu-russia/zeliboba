p = 'docs/KBL.md'
s = open(p, encoding='utf-8').read()

old = """1. **Карта памяти после включения MMU.** Покрыт только VA `0x40000000..0x40003FFF`
   (см. таблицу выше), а код KBL живёт по VA `0x40020000`. Проверить три версии:
   (а) писатель L1 (`0x4003A824`) считает индекс как `(VA >> 20) & 0x3FF`
   (наблюдаемая запись в TTBR1[0] при VA `0x40000000` выглядит именно так — тогда
   наша модель `ArmMmu` с немаскированным индексом (`arm_mmu.cpp:227`) расходится
   с ожиданием кода); (б) KBL копирует себя/векторы в PA `0x40118000` и прыгает по
   отображённому VA; (в) аргументы L1/L2-писателей (поля конфигурации `+0x40`
   TTBR0, `+0x54` split, `+0x60` TTBR1, `+0x170..0x178`) в нашей эмуляции
   отличаются от задуманных."""
new = """1. **Карта памяти: KBL строит её не с нуля.** Наблюдения:

   * блок `0x40020E48..0x400211xx` **не содержит циклов** и делает всего пять
     вызовов: три раза обёртку `0x40020A98` (секционные отображения: 16 МиБ по
     `0x50000000`, 1 МиБ, 16 МиБ) и по одному разу писателя L1 `0x4003A824`
     и заливку L2 `0x4003AB04`;
   * писатель L1 получает `r0 = 0x4010C000` (TTBR1), `r2 = 0` (индекс), `r3 =
     0x80200000` (L2), а `r11 = 0x40000000` — то есть индекс считается
     **относительно границы split**, а не как `VA >> 20`;
   * итог: TTBR0 — целиком fault, TTBR1 — только индекс 0 (L2 на `0x80200000`),
     L2 — 4 записи (VA `0x40000000..0x40003FFF` → PA `0x40118000..`, а по этому PA
     в нашем прогоне **нули**);
   * `info` показывает `TTBCR=0x2 (N=2)`, а первый fault — это fetch по
     VA `0x40039FC8` внутри самого хелпера включения MMU (`0x40039F94`), где наша
     `ArmMmu` берёт `L1[(VA>>20)&0xFFF] = 0x4010D000` (немаскированный индекс,
     `arm_mmu.cpp:227`).

   Отсюда рабочая версия: **основную карту (identity + устройства + трамплин
   `0x40118000`) строит предыдущая стадия — ARM boot ROM**, а KBL лишь дописывает
   свои участки. Наш `arm_boot_rom_stage_second_loader()` этого не делает: он
   только кладёт образ в SRAM и прыгает на `0x40020000`. Следующий шаг — либо
   смоделировать таблицы boot ROM (identity-карта для `0x00000000..0xC0000000`,
   устройства `0xE0000000..`, трамплин), либо доказать, что KBL строит карту сам
   (тогда разбираться, почему пять вызовов дают лишь 16 КиБ отображений)."""
assert old in s
s = s.replace(old, new, 1)
open(p, 'w', encoding='utf-8').write(s)
print('docs updated')
