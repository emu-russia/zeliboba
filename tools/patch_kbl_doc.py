p = 'docs/KBL.md'
s = open(p, encoding='utf-8').read()

old_start = s.index('## Что осталось')
new_tail = '''## Где KBL находится сейчас (обновлено)

После исправления Thumb-2-декодера KBL прошёл дальше и на сегодня проходит:

1. `PL310`/`GPIO`/`SC` (`0xE3101124`, `0xE3102100`, `0xE3102124`);
2. **подъём периферийного блока `0xE2040000`** — helper `0x4003BBCC` пишет
   `+0x04`, `+0x10`, `+0x20`, `+0x30`, `+0x40`, `+0x50`, `+0x60`, `+0x64`,
   ждёт бит `+0x28` (`0x4003BC98` — бит 8, `0x4003BCCC` — бит 9) и пишет `+0x70`;
   базы берутся из таблицы `0x4005C058` = `{0xE2030000 … 0xE2090000}`;
3. **рукопожатие `0xE5888000`** (`0x400217FA..0x40021872`): пишет 2 в `+0x00`/`+0x08`,
   ждёт `0x44` в `+0x20`, пишет 1, ждёт `0x11`, затем `0x302` в `+0x100`/`+0x108`,
   1 в `+0x180` и маркер `0xDEADCAFE` в `0x80000000` (DRAM) — **маркер проверен**;
4. входит в **построитель таблиц MMU** (`0x40020E48`) и здесь застревает:
   обёртка `0x40020A98` → `0x4003A9D4` (заполнение секционных дескрипторов,
   `arg4 >> 20` штук по 1 МиБ) вызывается снова и снова **с теми же аргументами**
   (`r0 = 0x5000158E`, `r6 = 0x50200000`, `r5 = 0x10`), а до программирования
   `TTBR0/TTBR1` (`0x40020C0E`) и включения MMU (`0x40020CA2`) дело не доходит.
   Внутри одного вызова цикл корректно считает до `r5` (проверено пошагово), так
   что повторяет именно вызывающий цикл — это следующая задача.

## Что осталось

1. **Цикл построителя карты памяти** (`0x40020E48`): выяснить, почему вызов
   `0x40020A98` повторяется с одинаковыми аргументами, и что за условие он ждёт
   (там читаются поля конфигурации из `.bss` KBL: `+0x40` = TTBR0, `+0x54`,
   `+0x60` = TTBR1, `+0x170..0x178` — аргументы отображения).
2. **SDIF/eMMC.** Отдельного ожидания `0xE2040028` больше нет: это глина
   питания/тактов, смоделированная как `Kermit.PeriphPower{N}` (биты 8 и 9 = «есть
   питание и такт»). Загрузка ядра идёт через SC/Ernie, а `Kermit.Sdif0`
   (`0xE0B00000`, как в таблице `sdif.elf` `0x81009FA8`) пока не задействован.
3. **Окно `0xE5888000`** — смоделировано (`Kermit.BootHandshake`): модель отвечает
   `0x44` после команды 2 и `0x11` после команды 1, потому что ни один модуль
   прошивки это окно не описывает. Это документированное допущение, а не реверс.
4. **MMU.** Отдельной правки не требуется: до `0x40020C0E` дело не доходит по
   причине из п. 1.
5. **CMeP.** Вторая стадия (`0x40000`) стоит на бесконечном `erepeat`-опросе
   `0xE3102100` и ждёт прерывания от SC — проводки прерываний MeP в модели нет.
'''
s = s[:old_start] + new_tail
open(p, 'w', encoding='utf-8').write(s)
print('KBL.md updated')
