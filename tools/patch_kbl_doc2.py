p = 'docs/KBL.md'
s = open(p, encoding='utf-8').read()

old = """4. входит в **построитель таблиц MMU** (`0x40020E48`) и здесь застревает:
   обёртка `0x40020A98` → `0x4003A9D4` (заполнение секционных дескрипторов,
   `arg4 >> 20` штук по 1 МиБ) вызывается снова и снова **с теми же аргументами**
   (`r0 = 0x5000158E`, `r6 = 0x50200000`, `r5 = 0x10`), а до программирования
   `TTBR0/TTBR1` (`0x40020C0E`) и включения MMU (`0x40020CA2`) дело не доходит.
   Внутри одного вызова цикл корректно считает до `r5` (проверено пошагово), так
   что повторяет именно вызывающий цикл — это следующая задача."""
new = """4. строит таблицы MMU (`0x40020E48`, обёртка `0x40020A98` → `0x4003A9D4`),
   программирует `TTBR0/TTBR1/TTBCR/DACR` (`0x40020C0E`, 295 556 шагов) и
   **включает MMU** (`0x40020CA2`, 302 622 шага);
5. после включения MMU получает data abort и уходит в двойной fault на векторе
   `0x0000000C`: `L1[0x40108000] = 0x1E0` (fault-дескриптор), то есть VA `0x0`
   (таблица векторов) в новой карте не отображён. Это следующая задача."""
assert old in s
s = s.replace(old, new, 1)

old2 = """1. **Цикл построителя карты памяти** (`0x40020E48`): выяснить, почему вызов
   `0x40020A98` повторяется с одинаковыми аргументами, и что за условие он ждёт
   (там читаются поля конфигурации из `.bss` KBL: `+0x40` = TTBR0, `+0x54`,
   `+0x60` = TTBR1, `+0x170..0x178` — аргументы отображения)."""
new2 = """1. **Карта памяти после включения MMU.** Вектор по VA `0x0` не отображён
   (`L1[0x40108000] = 0x1E0`), поэтому первый же data abort превращается в двойной
   fault. Нужно понять, каких записей не хватает: либо какой-то участок карты не
   был построен (поле конфигурации KBL в `.bss`: `+0x40` = TTBR0, `+0x54`,
   `+0x60` = TTBR1, `+0x170..0x178` — аргументы отображения), либо модель MMU
   (`ArmMmu`) отдаёт не то, что ожидает код.

   Важная деталь: до этой правки KBL вообще не доходил до `0x40020C0E` — его
   зацикливал `AND.W` (см. грабли ниже), поэтому раньше наблюдавшийся «MMU on с
   пустыми таблицами» был не отдельной проблемой, а следствием."""
assert old2 in s
s = s.replace(old2, new2, 1)

# document the AND.W grabli
old3 = """* **`STR.W`/`LDR.W` с пост-инкрементом** не делали writeback базы → бесконечный цикл
  очистки `.bss` (0x400211E0)."""
new3 = """* **`STR.W`/`LDR.W` с пост-инкрементом** не делали writeback базы → бесконечный цикл
  очистки `.bss` (0x400211E0).
* **`AND.W Rd, Rn, Rm` (группа `1110 1010`) исполнялся как сдвиг по регистру.**
  В `thumb32_data_processing_shifted()` было особое правило «opc == 0, type == 0,
  imm3:imm2 == 0 → сдвиг по регистру», которое перехватывало `AND.W Rd, Rn, Rm`
  (`EA03 0302` = `and.w r3, r3, r2`, подтверждено capstone). Настоящие сдвиги по
  регистру (`LSL/LSR/ASR/ROR.W`) живут в группе `1111 1010 op1 Rn | 1111 Rd 0000 00 Rm`
  (`FA03 F002` = `lsl.w r0, r3, r2`) и раньше вообще не исполнялись — они попадали
  в `MUL/MLA`. Из-за этого зацикливался построитель карты памяти: проверка
  «`(размер-1) & счётчик == 0`» (тест на степень двойки) не работала. Обе части
  исправлены, добавлены тесты `thumb2_section_fill_loop_head` и
  `thumb2_register_controlled_shifts`."""
assert old3 in s
s = s.replace(old3, new3, 1)
open(p, 'w', encoding='utf-8').write(s)
print('docs updated')
