p = 'docs/KBL.md'
s = open(p, encoding='utf-8').read()

old = """   Отсюда рабочая версия: **основную карту (identity + устройства + трамплин
   `0x40118000`) строит предыдущая стадия — ARM boot ROM**, а KBL лишь дописывает
   свои участки. Наш `arm_boot_rom_stage_second_loader()` этого не делает: он
   только кладёт образ в SRAM и прыгает на `0x40020000`. Следующий шаг — либо
   смоделировать таблицы boot ROM (identity-карта для `0x00000000..0xC0000000`,
   устройства `0xE0000000..`, трамплин), либо доказать, что KBL строит карту сам
   (тогда разбираться, почему пять вызовов дают лишь 16 КиБ отображений)."""
new = """   При этом KBL **отображает много регионов**: сразу после заливки L2 идёт длинная
   развёрнутая (без циклов) последовательность вызовов
   (`0x4002110E..0x40021xxx`): обёртки `0x40020AE4`, `0x40020A98` и хелперы
   `0x4003AD40`, `0x4003A9D4`, читающие пары полей конфигурации
   (`config[0xb0]/[0xb4]`, `[0xe0]/[0xe4]`, `[0x40]/[0x44]`, `[0x60]/[0x64]`,
   `[0x98]/[0x9c]`, `[0xcc]`, `config[0x78]` как смещение). Сама конфигурация в
   `.bss` заполнена правильно: `config[0x40] = 0x40108000` (TTBR0),
   `config[0x60] = 0x4010C000` (TTBR1), `config[0x0C] = 0x40000000` (split),
   сигнатура `0xCBAC03AA` в `0x400B2EC4`, указатель на конфиг `0x400B2EC8`.

   Значит карта строится самим KBL, а в наших таблицах она не появляется —
   следующий шаг: инструментировать аргументы хелперов (`r0` = база таблицы,
   `arg3` = VA, `arg4` = размер) на **каждом** вызове после исправления `AND.W`
   (прежняя выборка аргументов была сделана ещё в зацикленном, «грязном» прогоне
   и потому недостоверна) и найти инструкцию, из-за которой запись уходит не в
   `0x40108000`/`0x4010C000`."""
assert old in s
s = s.replace(old, new, 1)
open(p, 'w', encoding='utf-8').write(s)
print('docs updated')
