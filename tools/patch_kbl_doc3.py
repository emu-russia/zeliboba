p = 'docs/KBL.md'
s = open(p, encoding='utf-8').read()

old = """5. после включения MMU получает data abort и уходит в двойной fault на векторе
   `0x0000000C`: `L1[0x40108000] = 0x1E0` (fault-дескриптор), то есть VA `0x0`
   (таблица векторов) в новой карте не отображён. Это следующая задача."""
new = """5. после включения MMU сразу получает prefetch abort (первая же выборка
   инструкции по VA `0x40020CA4` не отображена), затем fault на векторе
   `0x0000000C` и двойной fault → останов.

   Разбор таблиц (`tools/dump_l1.py`, дампы через `mem` с активным ядром ARM):

   | Таблица | Что в ней |
   |---|---|
   | TTBR0 `0x40108000` (1024 записи) | **все** `0x000001E0` — fault-дескрипторы |
   | TTBR1 `0x4010C000` (2048 записей) | ровно одна валидная: индекс 0 = `0x80200181` — указатель на L2-таблицу |
   | L2 `0x80200000` | записи 0..3 = `0x4011844E`… (small page, VA `0x40000000..0x40003FFF` → PA `0x40118000..0x4011BFFF`), остальное — 0 (fault) |

   То есть карта покрывает только VA `0x40000000..0x40003FFF`, а **собственный код
   KBL по VA `0x40020000` не отображён** — отсюда падение сразу после `SCTLR.M = 1`.

   При этом блок построения карты (`0x40020E48..0x400211xx`) **не содержит циклов**
   (проверены все ветвления назад в диапазоне `0x40020E00..0x40021300`): он делает
   три вызова обёртки `0x40020A98` (`0x40021072`, `0x4002108E`, `0x400210AC`) и
   вызовы писателя L1 `0x4003A824` (`0x40021102`) и заливки L2 `0x4003AB04`
   (`0x4002110A`); все пять достигаются (294 047 / 294 060 шагов)."""
assert old in s
s = s.replace(old, new, 1)

old2 = """1. **Карта памяти после включения MMU.** Вектор по VA `0x0` не отображён
   (`L1[0x40108000] = 0x1E0`), поэтому первый же data abort превращается в двойной
   fault. Нужно понять, каких записей не хватает: либо какой-то участок карты не
   был построен (поле конфигурации KBL в `.bss`: `+0x40` = TTBR0, `+0x54`,
   `+0x60` = TTBR1, `+0x170..0x178` — аргументы отображения), либо модель MMU
   (`ArmMmu`) отдаёт не то, что ожидает код."""
new2 = """1. **Карта памяти после включения MMU.** Покрыт только VA `0x40000000..0x40003FFF`
   (см. таблицу выше), а код KBL живёт по VA `0x40020000`. Проверить три версии:
   (а) писатель L1 (`0x4003A824`) считает индекс как `(VA >> 20) & 0x3FF`
   (наблюдаемая запись в TTBR1[0] при VA `0x40000000` выглядит именно так — тогда
   наша модель `ArmMmu` с немаскированным индексом (`arm_mmu.cpp:227`) расходится
   с ожиданием кода); (б) KBL копирует себя/векторы в PA `0x40118000` и прыгает по
   отображённому VA; (в) аргументы L1/L2-писателей (поля конфигурации `+0x40`
   TTBR0, `+0x54` split, `+0x60` TTBR1, `+0x170..0x178`) в нашей эмуляции
   отличаются от задуманных."""
assert old2 in s
s = s.replace(old2, new2, 1)
open(p, 'w', encoding='utf-8').write(s)
print('docs updated')
