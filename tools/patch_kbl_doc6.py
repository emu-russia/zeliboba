p = 'docs/KBL.md'
s = open(p, encoding='utf-8').read()

# Replace the open IT question with the resolution.
start = s.index('## Открытый вопрос: `IT`-блоки и `ite hs` (не исправлено)')
end = s.index('## Грабли (уже исправленные)')
resolved = """## Исправлено: `IT`-блоки (`ite`) и глина блока `0xE2030000`

**`IT`-блоки.** Бит `E` в маске `IT` не инвертировал условие: `thumb_condition()`
возвращала `firstcond` для всех инструкций блока, поэтому в `ite` выполнялись обе
ветви. Это и ломало построение карты памяти: обёртка `0x40020A98` выбирает таблицу
именно так —

```
40020AA8  cmp r2, r4
40020AAC  ite hs
40020AAE  ldrhs r0, [r0, #0x40]     ; TTBR0
40020AB0  ldrlo r0, [r0, #0x60]     ; TTBR1
```

— поэтому хелпер получал указатель на конфиг вместо базы таблицы, и секционные
дескрипторы уезжали в `.bss`. Модель приведена к ARM ARM: `ITSTATE = firstcond[3:1]
: mask[4:0]`, условие — `ITSTATE[7:4]`, бит 4 приходит из сдвига маски, конец блока —
`ITSTATE[2:0] == 0`. Тесты: `thumb_it_block_it_else` (переписан на `mov.w`, потому
что `movs` в «then» честно меняет Z и тогда «else» обязан выполниться),
`thumb_it_block_conditional_ldr` (та же связка `ldrhs`/`ldrlo`, что у KBL).

**Глина блока `0xE2030000`.** `Kermit.Uart` (окно `0x100`) перекрывает glue-регистр
`+0x28`, а `Bus::find_device()` выбирает меньшее окно, поэтому ожидание бита 9
читало UART-регистр и висело. UART теперь отдаёт `+0x28 = 0x300` (питание/такт есть),
как и `Kermit.PeriphPower{N}`.

**Результат.** Карта памяти строится правильно (`tools/dump_l1.py`):

```
TTBR0[0x1A0] = 0x1A010182  section  (0x1A000000, PL310)
TTBR1[0x400] = 0x4001158E  section  (0x40000000, identity — код KBL)
TTBR1[0x500..0x51F]         section  (0x50000000.., staging)
```

KBL проходит включение MMU и **исполняется с включённой MMU** (667 трансляций,
313 465 инструкций ARM). Первый fault теперь:

```
fault[0]: VA=0x4003AFB6 fetch domain fault, domain=12,
          TTBR1 L1[0x4010D000]=0x4001158E
```

То есть отображение есть, но домен 12 запрещён: `DACR` KBL берёт из конфигурации
(`0x40020C36: mcr p15,0,r2,c3,c0,0`, r2 = `config[off+0x1AC]`) и в нашем прогоне
там `0x00000001` (клиент домена 0), а дескрипторы секций несут домен 12. Дальше —
понять, почему эти две величины расходятся (вероятно, поле конфигурации, которое на
железе дописывает ARM boot ROM).

## Грабли (уже исправленные)"""
s = s[:start] + resolved + s[end + len('## Грабли (уже исправленные)'):]
open(p, 'w', encoding='utf-8').write(s)
print('docs updated')
